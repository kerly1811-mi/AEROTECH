bool esTierra(double lat, double lon) {
  final banda = ((lat / 4).round() * 4).clamp(-56, 80);
  final tramos = _bandas[banda];
  if (tramos == null) return false;
  for (final t in tramos) {
    if (lon >= t[0] && lon <= t[1]) return true;
  }
  return false;
}
